#!/usr/bin/env python3
"""The UI font (Nunito ExtraBold, SIL OFL – picked by the user 2026-10-27, step 08) -> TFT_eSPI smooth fonts.

usage (needs Pillow: .scratch/venv/bin/python):
  font_convert.py            write firmware/kalos-dex/include/fonts/nunito_xb.inc + .scratch/previews/ui/font_fw.png
  font_convert.py --check    exit 1 if the file on disk differs

Writes one .vlw font per size (the format TFT_eSPI's loadFont() reads: header, 7 numbers per glyph, then the
8-bit alpha bitmaps) as C arrays. ASCII 33..126 only; the space is left out on purpose – TFT_eSPI then uses its
own space width. The preview is drawn FROM the arrays, so it shows what the gadget will draw.
"""
import struct, sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

KD = Path(__file__).resolve().parents[1]
TTF = KD / "assets/fonts/Nunito-wght.ttf"
OUT = KD / "firmware/kalos-dex/include/fonts/nunito_xb.inc"
PREVIEW = KD.parent / ".scratch/previews/ui/font_fw.png"
WEIGHT = 800                                       # ExtraBold
SIZES = {"SMALL": 12, "BODY": 15, "TITLE": 22}     # ~ the built-in fonts 1 / 2 / 4
CHARS = [chr(c) for c in range(33, 127)]


def load(size):
    f = ImageFont.truetype(str(TTF), size)
    f.set_variation_by_axes([WEIGHT])
    return f


def vlw(size):
    f = load(size)
    metrics, bitmaps = [], []
    for ch in CHARS:
        l, t, r, b = f.getbbox(ch, anchor="ls")   # relative to the pen on the baseline
        w, h = max(r - l, 0), max(b - t, 0)
        im = Image.new("L", (max(w, 1), max(h, 1)), 0)
        ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor="ls")
        bitmaps.append(im.tobytes()[: w * h] if w and h else b"")
        metrics.append((ord(ch), h, w, round(f.getlength(ch)), -t, l, 0))
    # TFT_eSPI takes the line height from the glyphs and only guesses the space from the header's ascent +
    # descent (x 2/7, ~6 px at 15 px – too wide); store a sum that gives Nunito's own space width instead.
    space = max(round(f.getlength(" ")), 2)
    ascent, descent = -(-space * 7 // 2), 0
    out = struct.pack(">6i", len(CHARS), 11, size, 0, ascent, descent)
    for m in metrics:
        out += struct.pack(">7i", *m)
    return out + b"".join(bitmaps)


def as_c(name, data):
    rows = [", ".join("0x%02X" % v for v in data[i : i + 24]) for i in range(0, len(data), 24)]
    return "static const uint8_t %s[%d] PROGMEM = {\n  %s\n};\n" % (name, len(data), ",\n  ".join(rows))


def render(data, text):   # draw like TFT_eSPI: glyph top = baseline - dY, left = pen + dX
    n = struct.unpack(">i", data[:4])[0]
    glyphs, ptr = {}, 24 + n * 28
    for i in range(n):
        u, h, w, adv, dy, dx, _ = struct.unpack(">7i", data[24 + i * 28 : 52 + i * 28])
        glyphs[chr(u)] = (h, w, adv, dy, dx, data[ptr : ptr + w * h])
        ptr += w * h
    asc = max(g[3] for g in glyphs.values())
    desc = max(g[0] - g[3] for g in glyphs.values())
    space = (struct.unpack(">i", data[16:20])[0] + struct.unpack(">i", data[20:24])[0]) * 2 // 7
    im = Image.new("L", (sum(glyphs[c][2] if c in glyphs else space for c in text) + 4, asc + desc + 4), 0)
    x = 2
    for c in text:
        if c not in glyphs:
            x += space
            continue
        h, w, adv, dy, dx, bm = glyphs[c]
        if w and h:
            im.paste(Image.frombytes("L", (w, h), bm), (x + dx, 2 + asc - dy))
        x += adv
    return im


def build():
    parts, fonts = [], {}
    for name, size in SIZES.items():
        fonts[name] = vlw(size)
        parts.append(as_c("FONT_%s" % name, fonts[name]))
    head = ("// GENERATED by tools/font_convert.py from assets/fonts/Nunito-wght.ttf (weight %d) – do not edit.\n"
            "// Nunito: Copyright 2014 The Nunito Project Authors, SIL Open Font License 1.1 (assets/fonts/OFL.txt).\n"
            "// Sizes: %s. Bytes: %s.\n" % (WEIGHT, ", ".join("%s %d px" % kv for kv in SIZES.items()),
                                             ", ".join("%s %d" % (k, len(v)) for k, v in fonts.items())))
    return head + "\n".join(parts), fonts


def main():
    text, fonts = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("font header %s" % ("fresh" if ok else "STALE – run tools/font_convert.py"))
        sys.exit(0 if ok else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    lines = ["Aegislash * Lv 36", "Food Fun Energy XP 310/780", "Knob direction  hold Feed+Play", "fw 0.6.0 #212"]
    shots = [render(fonts[n], s) for n in SIZES for s in lines]
    sheet = Image.new("L", (max(s.width for s in shots), sum(s.height for s in shots)), 0)
    y = 0
    for s in shots:
        sheet.paste(s, (0, y))
        y += s.height
    sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(PREVIEW)
    print("wrote %s (%s bytes) + %s" % (OUT.name, " + ".join(str(len(v)) for v in fonts.values()), PREVIEW.name))


if __name__ == "__main__":
    main()
